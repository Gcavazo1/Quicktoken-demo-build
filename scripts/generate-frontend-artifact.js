/**
 * @title Generate Frontend Artifact Script
 * @description Script to generate the simplified QuickTokenArtifact.ts for the frontend
 *              from the canonical Hardhat artifact JSON file.
 * 
 * Run with: node scripts/generate-frontend-artifact.js
 * Or after compile: npx hardhat compile && node scripts/generate-frontend-artifact.js
 */

const fs = require('fs');
const path = require('path');

// --- Configuration ---
const SOURCE_ARTIFACT_PATH = path.join(__dirname, '../artifacts/contracts/QuickToken.sol/QuickToken.json');
const TARGET_ARTIFACT_PATH = path.join(__dirname, '../admin-dashboard/src/lib/QuickTokenArtifact.ts');
// ---------------------

/**
 * Helper function to ensure bytecode starts with 0x for ethers.js v6
 * (Copied from the original QuickTokenArtifact.ts)
 */
function cleanBytecode(bytecode) {
  if (!bytecode || typeof bytecode !== 'string') {
    console.warn('Invalid or empty bytecode received, returning "0x"');
    return '0x';
  }
  // Ensure bytecode starts with 0x, remove existing if present to avoid duplication
  return '0x' + bytecode.replace(/^0x/, '');
}

/**
 * Main function to generate the artifact file.
 */
function generateArtifact() {
  console.log(`Reading source artifact from: ${SOURCE_ARTIFACT_PATH}`);

  if (!fs.existsSync(SOURCE_ARTIFACT_PATH)) {
    console.error('Error: Source artifact file not found.');
    console.error(`Please run 'npx hardhat compile' first.`);
    process.exit(1);
  }

  try {
    // Read and parse the source artifact
    const artifactJson = fs.readFileSync(SOURCE_ARTIFACT_PATH, 'utf8');
    const fullArtifact = JSON.parse(artifactJson);

    const { contractName, abi, bytecode, metadata } = fullArtifact;

    if (!abi || !bytecode || !contractName) {
      console.error('Error: Source artifact is missing required fields (contractName, abi, bytecode).');
      process.exit(1);
    }

    const cleanedBytecode = cleanBytecode(bytecode);
    const compilerVersion = metadata?.compiler?.version || 'unknown';

    // Construct the TypeScript file content
    const tsContent = `// Auto-generated by scripts/generate-frontend-artifact.js
// Do not edit this file manually!
// Source: ${path.basename(SOURCE_ARTIFACT_PATH)}
// Compiler: ${compilerVersion}

/**
 * Helper function to ensure bytecode starts with 0x for ethers.js v6
 */
function cleanBytecode(bytecode: string): string {
  if (!bytecode || typeof bytecode !== 'string') {
    console.warn('Invalid or empty bytecode received, returning "0x"');
    return '0x';
  }
  // Ensure bytecode starts with 0x, remove existing if present to avoid duplication
  return '0x' + bytecode.replace(/^0x/, ''); 
}

/**
 * QuickToken contract interface for ethers.js v6
 * Automatically generated from Hardhat artifact - DO NOT EDIT MANUALLY
 */
export const QuickTokenInterface = {
  contractName: "${contractName}",
  // ABI (Application Binary Interface)
  abi: ${JSON.stringify(abi, null, 2)},
  // Contract bytecode - cleaned for ethers.js v6 compatibility
  bytecode: cleanBytecode("${cleanedBytecode.substring(2)}"), // Pass raw bytecode without 0x to cleanBytecode
  metadata: ${JSON.stringify(metadata || {}, null, 2)}
};

// For backwards compatibility with code that may use default export
export default QuickTokenInterface;
`;

    console.log(`Generating frontend artifact at: ${TARGET_ARTIFACT_PATH}`);
    fs.writeFileSync(TARGET_ARTIFACT_PATH, tsContent, 'utf8');
    console.log('✅ Frontend artifact generated successfully!');

  } catch (error) {
    console.error('Error generating frontend artifact:', error);
    process.exit(1);
  }
}

// Run the generation function
generateArtifact(); 